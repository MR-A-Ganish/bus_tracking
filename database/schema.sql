-- Smart College Bus System schema for PostgreSQL.
-- Run this against the database selected by DATABASE_URL before running seed.py.

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('student', 'driver', 'admin'))
);

-- Supports existing databases that were created before the driver role.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check
    CHECK (role IN ('student', 'driver', 'admin'));

CREATE TABLE IF NOT EXISTS routes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_name VARCHAR(100) NOT NULL,
    start_point VARCHAR(100) NOT NULL,
    end_point VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS bus_stops (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id INTEGER NOT NULL REFERENCES routes(id),
    stop_name VARCHAR(100) NOT NULL,
    sequence_order INTEGER NOT NULL,
    distance_from_start_km REAL NOT NULL,
    latitude NUMERIC(10,6),
    longitude NUMERIC(10,6)
);

CREATE TABLE IF NOT EXISTS buses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_name VARCHAR(50) NOT NULL,
    driver_name VARCHAR(100),
    capacity INTEGER NOT NULL DEFAULT 50,
    current_passengers INTEGER NOT NULL DEFAULT 0,
    route_id INTEGER NOT NULL REFERENCES routes(id)
);

CREATE TABLE IF NOT EXISTS students (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    name VARCHAR(100) NOT NULL,
    register_no VARCHAR(50),
    phone VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS admins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS drivers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES users(id),
    name VARCHAR(100) NOT NULL,
    bus_id INTEGER NOT NULL UNIQUE REFERENCES buses(id)
);

CREATE TABLE IF NOT EXISTS student_bus_assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students(id),
    bus_id INTEGER NOT NULL REFERENCES buses(id),
    stop_id INTEGER NOT NULL REFERENCES bus_stops(id)
);

CREATE TABLE IF NOT EXISTS bus_locations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id INTEGER NOT NULL UNIQUE REFERENCES buses(id),
    distance_covered_km REAL NOT NULL DEFAULT 0,
    current_stop_id INTEGER REFERENCES bus_stops(id),
    next_stop_id INTEGER REFERENCES bus_stops(id),
    status VARCHAR(20) NOT NULL DEFAULT 'not_started'
        CHECK (status IN ('not_started', 'moving', 'arrived_at_stop', 'waiting', 'reached_college')),
    traffic_condition VARCHAR(10) NOT NULL DEFAULT 'low'
        CHECK (traffic_condition IN ('low', 'medium', 'high')),
    speed_kmph REAL NOT NULL DEFAULT 30,
    college_entry_detected BOOLEAN NOT NULL DEFAULT FALSE,
    college_entry_time TIMESTAMP,
    last_updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS attendance (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students(id),
    bus_id INTEGER NOT NULL REFERENCES buses(id),
    stop_id INTEGER NOT NULL REFERENCES bus_stops(id),
    attendance_date DATE NOT NULL,
    attendance_time TIME NOT NULL,
    boarding_status VARCHAR(10) NOT NULL DEFAULT 'boarded' CHECK (boarding_status = 'boarded'),
    UNIQUE (student_id, bus_id, attendance_date)
);

CREATE TABLE IF NOT EXISTS notifications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_role VARCHAR(10) NOT NULL DEFAULT 'all' CHECK (target_role IN ('student', 'admin', 'all')),
    bus_id INTEGER REFERENCES buses(id),
    student_id INTEGER,
    message VARCHAR(255) NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS eta_predictions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id INTEGER NOT NULL REFERENCES buses(id),
    stop_id INTEGER NOT NULL REFERENCES bus_stops(id),
    predicted_eta_minutes REAL NOT NULL,
    distance_km REAL NOT NULL,
    traffic_condition VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION set_bus_locations_last_updated()
RETURNS TRIGGER AS $$
BEGIN
    NEW.last_updated = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS bus_locations_last_updated ON bus_locations;
CREATE TRIGGER bus_locations_last_updated
BEFORE UPDATE ON bus_locations
FOR EACH ROW EXECUTE FUNCTION set_bus_locations_last_updated();

